/**
 * Text substitutions available in text and badge layers.
 *
 * Deliberately limited to what Vision Studio knows: the product's own metadata
 * and the vision engine's findings. There is no price, no discount, no
 * inventory — this application does not model commerce.
 */
export const TEMPLATE_VARIABLES = [
  { key: '{{product_name}}', label: 'Product name', example: 'Ribbed Knit Midi Dress' },
  { key: '{{category}}', label: 'Category', example: 'Dresses' },
  { key: '{{folder}}', label: 'Source folder', example: 'AW25/dresses' },
  { key: '{{file_name}}', label: 'File name', example: 'look-01.jpg' },
  { key: '{{shot_type}}', label: 'Detected shot type', example: 'full_body' },
  { key: '{{garment_type}}', label: 'Detected garment type', example: 'full_outfit' },
  { key: '{{index}}', label: 'Image index within product', example: '1' },
] as const

export interface TemplateVariableValues {
  product_name: string
  category: string
  folder: string
  file_name: string
  shot_type: string
  garment_type: string
  index: string
}

export function resolveTemplateVariables(
  content: string,
  values: Partial<TemplateVariableValues>
): string {
  return content.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
    const value = (values as Record<string, string | undefined>)[key]
    return value ?? match
  })
}

// ─── Layer factories ─────────────────────────────────────────────────────────

let layerCounter = 0
function nextLayerId(): string {
  // Not cryptographic — layer ids only need to be unique within a document.
  layerCounter += 1
  return `layer_${Date.now().toString(36)}_${layerCounter.toString(36)}`
}

export function createLayer(type: LayerType, zIndex: number): Layer {
  const base: BaseLayer = {
    id: nextLayerId(),
    type,
    name: type.charAt(0).toUpperCase() + type.slice(1),
    x: 10,
    y: 10,
    width: 40,
    height: 12,
    rotation: 0,
    opacity: 1,
    zIndex,
    visible: true,
    locked: false,
    anchorTo: null,
  }

  switch (type) {
    case 'text':
      return {
        ...base,
        type: 'text',
        name: 'Text',
        content: '{{product_name}}',
        fontFamily: 'Inter',
        fontSizePct: 4,
        fontWeight: 'bold',
        color: '#111111',
        align: 'left',
        lineHeight: 1.2,
        letterSpacing: 0,
        wrap: true,
        backgroundColor: null,
        paddingPct: 0,
        borderRadiusPct: 0,
        uppercase: false,
      }
    case 'image':
      return {
        ...base,
        type: 'image',
        name: 'Image',
        assetKey: '',
        fit: 'contain',
        borderRadiusPct: 0,
      }
    case 'rectangle':
      return {
        ...base,
        type: 'rectangle',
        name: 'Rectangle',
        fill: '#111111',
        borderRadiusPct: 0,
        strokeColor: null,
        strokeWidthPct: 0,
      }
    case 'ellipse':
      return {
        ...base,
        type: 'ellipse',
        name: 'Ellipse',
        width: 20,
        height: 20,
        fill: '#111111',
        strokeColor: null,
        strokeWidthPct: 0,
      }
    case 'badge':
      return {
        ...base,
        type: 'badge',
        name: 'Badge',
        width: 22,
        height: 7,
        content: 'NEW IN',
        fill: '#111111',
        color: '#ffffff',
        fontFamily: 'Inter',
        fontSizePct: 2.4,
        fontWeight: 'bold',
        shape: 'pill',
        uppercase: true,
      }
  }
}
