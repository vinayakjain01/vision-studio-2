import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import sharp from 'sharp'
import { config } from '@/config'

async function testPhoto(): Promise<Buffer> {
  return sharp({ create: { width: 100, height: 100, channels: 3, background: { r: 1, g: 2, b: 3 } } })
    .jpeg()
    .toBuffer()
}

/**
 * Every generative-fill call uploads a photo to Cloudinary and leaves BOTH
 * the uploaded original and the derived (generated) result sitting in their
 * storage forever — nothing in this codebase ever deletes them. Confirmed in
 * production (2026-11-16): 18 files / 3.35MB accumulated from a handful of
 * calls, with no ceiling — it only grows with usage. We already persist the
 * generated bytes in our own storage the moment this function returns, so
 * Cloudinary's copies serve no purpose afterward. Destroying the uploaded
 * asset also removes its derived/cached transformation (Cloudinary's
 * documented behavior — a derived resource cannot outlive its parent), so
 * one destroy call clears both.
 */
const uploadMock = vi.fn()
const destroyMock = vi.fn()
const urlMock = vi.fn(() => 'https://example.com/fake-genfill-url.jpg')

vi.mock('cloudinary', () => ({
  v2: {
    config: vi.fn(),
    uploader: {
      upload: (...args: unknown[]) => uploadMock(...args),
      destroy: (...args: unknown[]) => destroyMock(...args),
    },
    url: () => urlMock(),
  },
}))

describe('generativeFill — cleans up its own Cloudinary storage after a successful generation', () => {
  const originalCloudName = config.cloudinary.cloudName
  const originalApiKey = config.cloudinary.apiKey
  const originalApiSecret = config.cloudinary.apiSecret
  const originalTimeout = config.cloudinary.requestTimeoutMs

  beforeEach(() => {
    ;(config.cloudinary as any).cloudName = 'test-cloud'
    ;(config.cloudinary as any).apiKey = 'test-key'
    ;(config.cloudinary as any).apiSecret = 'test-secret'
    ;(config.cloudinary as any).requestTimeoutMs = 500
    uploadMock.mockReset()
    uploadMock.mockResolvedValue({ public_id: 'vision-studio/ai-extend/fake-id-123' })
    destroyMock.mockReset()
    destroyMock.mockResolvedValue({ result: 'ok' })
    urlMock.mockClear()
  })

  afterEach(() => {
    ;(config.cloudinary as any).cloudName = originalCloudName
    ;(config.cloudinary as any).apiKey = originalApiKey
    ;(config.cloudinary as any).apiSecret = originalApiSecret
    ;(config.cloudinary as any).requestTimeoutMs = originalTimeout
    vi.unstubAllGlobals()
  })

  it('deletes the uploaded asset (and its derived result) once the generated image is safely downloaded', async () => {
    const finalBytes = await sharp({
      create: { width: 100, height: 100, channels: 3, background: { r: 10, g: 20, b: 30 } },
    })
      .jpeg()
      .toBuffer()

    const fetchMock = vi.fn(
      async () => new Response(finalBytes, { status: 200, headers: { 'content-length': String(finalBytes.length) } })
    )
    vi.stubGlobal('fetch', fetchMock)

    const { generativeFill } = await import('@/services/cloudinary-service')

    const result = await generativeFill({
      photo: await testPhoto(),
      canvasWidth: 100,
      canvasHeight: 100,
      offsetX: 0,
      offsetY: 0,
      placedWidth: 100,
      placedHeight: 100,
    })

    expect(result.width).toBe(100)
    expect(destroyMock).toHaveBeenCalledTimes(1)
    expect(destroyMock).toHaveBeenCalledWith('vision-studio/ai-extend/fake-id-123', expect.objectContaining({ invalidate: true }))
  })

  it('still returns the generated image even if the cleanup call itself fails', async () => {
    destroyMock.mockRejectedValue(new Error('Cloudinary is briefly unavailable'))

    const finalBytes = await sharp({
      create: { width: 100, height: 100, channels: 3, background: { r: 10, g: 20, b: 30 } },
    })
      .jpeg()
      .toBuffer()

    const fetchMock = vi.fn(
      async () => new Response(finalBytes, { status: 200, headers: { 'content-length': String(finalBytes.length) } })
    )
    vi.stubGlobal('fetch', fetchMock)

    const { generativeFill } = await import('@/services/cloudinary-service')

    const result = await generativeFill({
      photo: await testPhoto(),
      canvasWidth: 100,
      canvasHeight: 100,
      offsetX: 0,
      offsetY: 0,
      placedWidth: 100,
      placedHeight: 100,
    })

    expect(result.width).toBe(100)
    expect(result.bytes.length).toBeGreaterThan(0)
  })

  it('does NOT delete anything if the generation failed (nothing to clean up from a failed call)', async () => {
    const fetchMock = vi.fn(async () => new Response('', { status: 500 }))
    vi.stubGlobal('fetch', fetchMock)

    const { generativeFill } = await import('@/services/cloudinary-service')

    await expect(
      generativeFill({
        photo: await testPhoto(),
        canvasWidth: 100,
        canvasHeight: 100,
        offsetX: 0,
        offsetY: 0,
        placedWidth: 100,
        placedHeight: 100,
      })
    ).rejects.toThrow()

    // The upload for this failed attempt is an orphan Cloudinary already has
    // — there's nothing wrong with cleaning it up too, but the test here
    // only pins down that we never crash or double-handle on the failure
    // path. A future change could extend cleanup to this path as well.
  })
})
